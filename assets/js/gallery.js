function getNumericIndexFromSrc(src) {
  if (!src) return 0;
  try {
    if (
      typeof metaBySrc !== "undefined" &&
      metaBySrc[src] &&
      typeof metaBySrc[src].index === "number"
    )
      return metaBySrc[src].index;
  } catch (e) {}
  try {
    const base = (src || "").split("/").pop() || "";
    const m = base.match(/(\d+)/);
    if (m && m[1]) return parseInt(m[1], 10) || 0;
  } catch (e) {}
  return 0;
}
