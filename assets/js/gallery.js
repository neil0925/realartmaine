function buildSynonymMap(groups) {
  const map = {};
  if (!Array.isArray(groups)) return map;
  groups.forEach((group) => {
    const normalized = group
      .map((g) => (g || "").toString().trim().toLowerCase())
      .filter(Boolean);
    normalized.forEach((term) => {
      map[term] = normalized.filter((t) => t !== term);
    });
  });
  return map;
}
