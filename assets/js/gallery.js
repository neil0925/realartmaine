function buildMetaTokens(meta) {
  const tokens = new Set();
  if (meta && Array.isArray(meta.tokens)) {
    meta.tokens.forEach((t) => {
      if (t) tokens.add(t);
    });
  }
  (meta.tags || []).forEach((t) => {
    const parts = t
      .split(/[\s,;]+/)
      .map(normToken)
      .filter(Boolean);
    parts.forEach((p) => tokens.add(p));
  });
  (meta.styles || []).forEach((s) => {
    const parts = s
      .split(/[\s,;]+/)
      .map(normToken)
      .filter(Boolean);
    parts.forEach((p) => tokens.add(p));
  });
  if (meta.crew) {
    meta.crew
      .split(/[\s,;]+/)
      .map(normToken)
      .filter(Boolean)
      .forEach((p) => tokens.add(p));
  }
  if (meta.photographer) {
    meta.photographer
      .split(/[\s,;]+/)
      .map(normToken)
      .filter(Boolean)
      .forEach((p) => tokens.add(p));
  }
  (meta.rawBase || "")
    .split(/[\s,;,_-]+/)
    .map(normToken)
    .filter(Boolean)
    .forEach((p) => tokens.add(p));
  try {
    const current = Array.from(tokens);
    current.forEach((t) => {
      if (t && SYNONYM_MAP && SYNONYM_MAP[t] && SYNONYM_MAP[t].length) {
        SYNONYM_MAP[t].forEach((s) => tokens.add(s));
      }
    });
  } catch (e) {}
  return tokens;
}
function parseYNFlag(value) {
  const norm = normToken(value);
  if (norm === "y" || norm === "yes" || norm === "true" || norm === "1") {
    return true;
  }
  if (norm === "n" || norm === "no" || norm === "false" || norm === "0") {
    return false;
  }
  return null;
}
function maybeExtractFreightFlags(parts) {
  const flags = {
    isMaineFreight: null,
    hasMaineWriters: null,
    hasNonMaineWriters: null,
  };
  const copy = Array.isArray(parts) ? parts.slice() : [];
  if (copy.length < 6) {
    return { parts: copy, flags };
  }
  const tail = copy.slice(-3).map(parseYNFlag);
  if (tail.every((v) => typeof v === "boolean")) {
    return {
      parts: copy.slice(0, -3),
      flags: {
        isMaineFreight: tail[0],
        hasMaineWriters: tail[1],
        hasNonMaineWriters: tail[2],
      },
    };
  }
  return { parts: copy, flags };
}

